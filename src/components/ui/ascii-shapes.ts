// Shape library for the "numbers as ink" motif: decorative figures drawn as a
// 28x18 grid of digit/operator glyphs. Density bitmaps are authored as string
// art (1-9 = ink density, "." = empty) so shapes stay human-editable in source.
// All shapes share the same grid so morphing is a per-cell interpolation.

export const ASCII_COLS = 28;
export const ASCII_ROWS = 18;

export type AsciiShapeName = "theta" | "times" | "bolt" | "trophy";

export type AsciiShape = {
  name: AsciiShapeName;
  cols: number;
  rows: number;
  density: Uint8Array;
};

function parseShape(name: AsciiShapeName, art: string): AsciiShape {
  const rows = art.trim().split("\n");
  const density = new Uint8Array(ASCII_COLS * ASCII_ROWS);
  for (let r = 0; r < ASCII_ROWS; r++) {
    const line = rows[r] ?? "";
    for (let c = 0; c < ASCII_COLS; c++) {
      const ch = line[c];
      density[r * ASCII_COLS + c] = ch && ch !== "." ? Number(ch) : 0;
    }
  }
  return { name, cols: ASCII_COLS, rows: ASCII_ROWS, density };
}

