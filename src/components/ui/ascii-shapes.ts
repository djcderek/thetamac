// Glyphs ordered by real ink coverage in Geist Mono, sparse to dense.
export const GLYPH_RAMP = [" ", "·", "+", "÷", "=", "7", "4", "3", "6", "0", "8"];

// Cells with density at or above this render in the brand accent when enabled.
export const ACCENT_THRESHOLD = 8;

export function hash3(x: number, y: number, t: number): number {
  let h = (x * 73856093) ^ (y * 19349663) ^ (t * 83492791);
  h = (h ^ (h >>> 13)) >>> 0;
  return h;
}

// Per-cell 0..1 offset used to stagger the morph so shapes dissolve
// cell-by-cell instead of crossfading.
export function cellPhase(x: number, y: number): number {
  return hash3(x, y, 7) / 4294967295;
}

// Map a (possibly interpolated) density to a glyph. The hash lets a cell
// shimmer between neighboring glyphs of similar weight without changing the
// overall brightness of the shape.
export function pickGlyph(density: number, x: number, y: number, tick: number): string {
  if (density <= 0.35) return " ";
  const base = Math.min(10, Math.max(1, Math.round((density / 9) * 10)));
  const h = hash3(x, y, tick);
  const jitter = h % 4 === 0 ? ((h >>> 3) % 2 === 0 ? -1 : 1) : 0;
  const idx = Math.min(10, Math.max(1, base + jitter));
  return GLYPH_RAMP[idx];
}
