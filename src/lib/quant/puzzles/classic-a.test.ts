import assert from "node:assert/strict";
import test from "node:test";
import { CLASSIC_A_PUZZLES } from "./classic-a";
import { value } from "../rational";
import { draws, faces } from "../test-helpers";

/** Every ordering of 1…n. */
const orders = (n: number) => draws(faces(n), n);

function choose(n: number, k: number): number {
  let result = 1;
  for (let i = 1; i <= k; i++) result = (result * (n - k + i)) / i;
  return result;
}

/** Each puzzle's answer worked out another way: brute force, a recursion, or a different count. */
const checks: Record<string, () => number> = {
  "monty-hall": () => {
    // Car behind each door, each first pick, each door the host may open (split evenly).
    let win = 0;
    for (let car = 0; car < 3; car++) {
      for (let pick = 0; pick < 3; pick++) {
        const hostDoors = [0, 1, 2].filter((d) => d !== pick && d !== car);
        for (const host of hostDoors) {
          const switchTo = [0, 1, 2].find((d) => d !== pick && d !== host)!;
          if (switchTo === car) win += 1 / 9 / hostDoors.length;
        }
      }
    }
    return win;
  },
  "bertrands-box": () => {
    // Each of the 6 coins is equally likely to be drawn; keep the gold draws.
    const boxes = [["G", "G"], ["S", "S"], ["G", "S"]];
    let gold = 0;
    let goldAndGold = 0;
    for (const box of boxes) {
      for (let i = 0; i < 2; i++) {
        if (box[i] !== "G") continue;
        gold++;
        if (box[1 - i] === "G") goldAndGold++;
      }
    }
    return goldAndGold / gold;
  },
  "lost-boarding-pass": () => {
    // p(n): chance the last of n gets their seat when the first sits at random.
    // The first takes seat 1 (fine), seat n (lost), or seat k, leaving the same problem with n − k + 1.
    const p: number[] = [0, 1, 0.5];
    for (let n = 3; n <= 100; n++) {
      let total = 1 / n;
      for (let k = 2; k <= n - 1; k++) total += p[n - k + 1] / n;
      p[n] = total;
    }
    return p[100];
  },
  "labelling-a-die": () => {
    // Faces: 0 up, 1 down, 2 front, 3 back, 4 left, 5 right. Rotations generated by two quarter turns.
    const turnA = [0, 1, 4, 5, 3, 2]; // spin about the up–down axis
    const turnB = [2, 3, 1, 0, 4, 5]; // tip forward about the left–right axis
    const apply = (labels: number[], turn: number[]) => turn.map((from) => labels[from]);
    const group = new Set<string>([JSON.stringify([0, 1, 2, 3, 4, 5])]);
    let frontier = [[0, 1, 2, 3, 4, 5]];
    while (frontier.length) {
      const next: number[][] = [];
      for (const r of frontier) {
        for (const turn of [turnA, turnB]) {
          const composed = apply(r, turn);
          const key = JSON.stringify(composed);
          if (!group.has(key)) {
            group.add(key);
            next.push(composed);
          }
        }
      }
      frontier = next;
    }
    assert.equal(group.size, 24);
    const rotations = [...group].map((s) => JSON.parse(s) as number[]);
    const seen = new Set<string>();
    let classes = 0;
    for (const labelling of orders(6)) {
      const key = JSON.stringify(labelling);
      if (seen.has(key)) continue;
      classes++;
      for (const r of rotations) seen.add(JSON.stringify(apply(labelling, r)));
    }
    return classes;
  },
  "locks-and-keys": () => {
    // A lock is a set of key holders. It must not stop any trio, so it can stop only
    // pairs whose complement holds every key. Count the pairs each allowed lock stops.
    const people = 5;
    let mostPairsOneLockStops = 0;
    for (let holders = 0; holders < 1 << people; holders++) {
      let stopsATrio = false;
      let pairsStopped = 0;
      for (let group = 0; group < 1 << people; group++) {
        const size = [...Array(people).keys()].filter((i) => group & (1 << i)).length;
        const stopped = (group & holders) === 0;
        if (size === 3 && stopped) stopsATrio = true;
        if (size === 2 && stopped) pairsStopped++;
      }
      if (!stopsATrio) mostPairsOneLockStops = Math.max(mostPairsOneLockStops, pairsStopped);
    }
    // Every pair must be stopped by some lock.
    return Math.ceil(choose(people, 2) / mostPairsOneLockStops);
  },
  "one-bubble-pass": () => {
    const all = orders(5);
    const sorted = all.filter((order) => {
      const a = [...order];
      for (let i = 0; i < a.length - 1; i++) if (a[i] > a[i + 1]) [a[i], a[i + 1]] = [a[i + 1], a[i]];
      return a.every((x, i) => i === 0 || a[i - 1] < x);
    });
    return sorted.length / all.length;
  },
  "odd-sums-grid": () => {
    let good = 0;
    let all = 0;
    for (const grid of orders(9)) {
      all++;
      const odd = (a: number, b: number, c: number) => (grid[a] + grid[b] + grid[c]) % 2 === 1;
      if (odd(0, 1, 2) && odd(3, 4, 5) && odd(6, 7, 8) && odd(0, 3, 6) && odd(1, 4, 7) && odd(2, 5, 8)) good++;
    }
    return good / all;
  },
  "evens-before-odds": () => {
    // Orders in which the faces first appear.
    const all = orders(6);
    return all.filter((o) => o.slice(0, 3).every((f) => f % 2 === 0)).length / all.length;
  },
  "knockout-meeting": () => {
    // Players ranked 1 (best) … n. Put player a in a slot; b lands in one of the other slots,
    // h of which make them meet in a round with half-blocks of size h. They meet then only if
    // each beats the other h − 1 players in their half-block. Average over pairs of ranks.
    const n = 128;
    let total = 0;
    for (let i = 1; i <= n; i++) {
      for (let j = i + 1; j <= n; j++) {
        for (let h = 1; h <= n / 2; h *= 2) {
          const worseThanJ = n - j;
          const worseThanIOthers = n - i - 1;
          if (worseThanJ < h - 1) continue;
          const ways = choose(worseThanJ, h - 1) * choose(worseThanIOthers - (h - 1), h - 1);
          const all = choose(n - 2, h - 1) * choose(n - 2 - (h - 1), h - 1);
          total += (h / (n - 1)) * (ways / all);
        }
      }
    }
    return total / choose(n, 2);
  },
  "best-two-final": () => {
    // Exhaustive for 8 players to confirm the halves argument, then the same count at 128.
    let final = 0;
    let all = 0;
    for (const slots of orders(8)) {
      all++;
      const best = slots.indexOf(1);
      const second = slots.indexOf(2);
      if (best < 4 !== second < 4) final++;
    }
    assert.equal(final / all, 4 / 7);
    // At 128: of the 127 slots for the second best, those in the other half.
    return [...Array(127).keys()].filter((slot) => slot >= 63).length / 127;
  },
  "card-after-first-ace": () => {
    // Sum over the first ace's position p: cards 1…p−1 come from the 47 cards that are neither
    // an ace nor the king of hearts, card p is an ace, card p + 1 is the king of hearts.
    let total = 0;
    for (let p = 1; p <= 48; p++) {
      let chance = 1;
      for (let k = 0; k < p - 1; k++) chance *= (47 - k) / (52 - k);
      chance *= 4 / (52 - (p - 1));
      chance *= 1 / (52 - p);
      total += chance;
    }
    return total;
  },
  "hundred-switches": () => {
    const on = Array(101).fill(false);
    for (let person = 1; person <= 100; person++) for (let s = person; s <= 100; s += person) on[s] = !on[s];
    return on.filter(Boolean).length;
  },
  "dealt-a-straight": () => {
    // Every set of 5 different ranks, checked for a run, times the suit choices that aren't a flush.
    let straights = 0;
    for (let a = 1; a <= 13; a++)
      for (let b = a + 1; b <= 13; b++)
        for (let c = b + 1; c <= 13; c++)
          for (let d = c + 1; d <= 13; d++)
            for (let e = d + 1; e <= 13; e++) {
              const run = e - a === 4;
              const aceHigh = a === 1 && b === 10 && c === 11 && d === 12 && e === 13;
              if (run || aceHigh) straights += 4 ** 5 - 4;
            }
    return straights;
  },
  "spinner-race": () => {
    // Step the race spin by spin: state = 5s seen so far (0 or 1).
    let zero = 1;
    let one = 0;
    let win = 0;
    for (let spin = 0; spin < 2000; spin++) {
      win += one / 7;
      const nextOne = zero / 7 + (one * 4) / 7;
      zero = (zero * 4) / 7;
      one = nextOne;
    }
    return win;
  },
};

test("every first-batch puzzle has a check, and its answer agrees with it", () => {
  for (const puzzle of CLASSIC_A_PUZZLES) {
    const check = checks[puzzle.id];
    assert.ok(check, `no check for ${puzzle.id}`);
    const expected = check();
    assert.ok(Math.abs(value(puzzle.problem.answer) - expected) < 1e-9, `${puzzle.id}: ${value(puzzle.problem.answer)} vs ${expected}`);
  }
});
